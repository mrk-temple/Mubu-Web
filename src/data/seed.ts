const DAY = 24 * 60 * 60 * 1000;

function iso(daysAgo: number, hour = 10, minute = 20): string {
  const d = new Date(Date.now() - daysAgo * DAY);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

